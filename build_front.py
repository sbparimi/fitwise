#!/usr/bin/env python3
"""Build 1 front-end assembler (22 Nov 2026).

Reads the page bodies in front/*.html (each starts with a <!--META {json} --> block) and wraps them with
the shared header (partials_header.html) and footer (partials_footer.html) into site/<name>.html.
Also regenerates partials.js so the Worker-rendered pages (/jobs, /j/<id>, /events, gate screens)
share the exact same header/footer markup.
Run via build.sh (after build_pages.py so the new pages win over any legacy generated file)."""
import os, re, json

D = os.path.dirname(os.path.abspath(__file__))
S = os.path.join(D, "site")
F = os.path.join(D, "front")
SITE = "https://fitwise.sites.tab.bot"
HEADER = open(os.path.join(D, "partials_header.html")).read().strip()
FOOTER = open(os.path.join(D, "partials_footer.html")).read().strip()

SHELL = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="{site}{path}">
<meta property="og:type" content="website"><meta property="og:site_name" content="Fitwise">
<meta property="og:title" content="{title}"><meta property="og:description" content="{desc}">
<meta property="og:url" content="{site}{path}"><meta property="og:image" content="{site}/og.png">
<meta name="twitter:card" content="summary_large_image">
<meta name="theme-color" content="#4F23E6">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="/v5.css">{head}
</head>
<body{bodyattr}>
<a class="skip" href="#main">Skip to content</a>
<!--HEADER-->
{header}
<!--/HEADER-->
<main id="main">
{body}
</main>
<!--FOOTER-->
{footer}
<!--/FOOTER-->
{scripts}
</body>
</html>
"""

META_RE = re.compile(r"^\s*<!--META\s*(\{.*?\})\s*-->", re.S)


def build_page(name):
    raw = open(os.path.join(F, name)).read()
    m = META_RE.match(raw)
    meta = json.loads(m.group(1)) if m else {}
    body = raw[m.end():] if m else raw
    html = SHELL.format(
        title=meta.get("title", "Fitwise"),
        desc=meta.get("desc", ""),
        path=meta.get("path", "/" + name.replace(".html", "")),
        site=SITE,
        head=meta.get("head", ""),
        bodyattr=(" " + meta["bodyattr"]) if meta.get("bodyattr") else "",
        header=HEADER,
        footer=FOOTER,
        body=body.strip(),
        scripts=meta.get("scripts", ""),
    )
    open(os.path.join(S, name), "w").write(html)
    return name, len(html)


def main():
    pages = sorted(f for f in os.listdir(F) if f.endswith(".html"))
    built = [build_page(p) for p in pages]
    # partials.js: one source of truth for the Worker-rendered pages
    js = ("// generated by build_front.py from partials_header.html / partials_footer.html\n"
          "const SITE_HEADER = " + json.dumps(HEADER) + ";\n"
          "const SITE_FOOTER = " + json.dumps(FOOTER) + ";\n")
    open(os.path.join(D, "partials.js"), "w").write(js)
    print("front pages: " + ", ".join("%s (%.1f KB)" % (n, b / 1024) for n, b in built))
    print("partials.js regenerated from the shared header/footer")


if __name__ == "__main__":
    main()
